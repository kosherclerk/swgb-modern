"""Extract the GLSL sources from shaders.cpp and compile them to SPIR-V
(Vulkan flavour, -DVULKAN) into build/shaders_vk.inc."""
import re, subprocess, sys, os, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'src/ddraw/backends/shaders.cpp'), encoding='utf-8').read()
blocks = re.findall(r'R"GLSL\((.*?)\)GLSL"', src, re.S)
assert len(blocks) == 3, len(blocks)
glslang = sys.argv[1]
out = ['// generated by tools/gen_vk_shaders.py - do not edit']
for (name, stage), body in zip([('kVkVertex', 'vert'), ('kVkPalette', 'frag'), ('kVkScale', 'frag')], blocks):
    with tempfile.TemporaryDirectory() as td:
        f = os.path.join(td, 's.' + stage)
        open(f, 'w').write('#version 450\n#define SWGBM_VK 1\n' + body)
        spv = os.path.join(td, 's.spv')
        subprocess.check_call([glslang, '-V', '-S', stage, f, '-o', spv], stdout=subprocess.DEVNULL)
        data = open(spv, 'rb').read()
    words = [int.from_bytes(data[i:i+4], 'little') for i in range(0, len(data), 4)]
    out.append('static const uint32_t %s[] = {%s};' % (name, ','.join('0x%08x' % w for w in words)))
os.makedirs(os.path.join(root, 'build'), exist_ok=True)
open(os.path.join(root, 'build/shaders_vk.inc'), 'w').write('\n'.join(out) + '\n')
print('vulkan shaders: ok')
